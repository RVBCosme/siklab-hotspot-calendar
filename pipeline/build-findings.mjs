// Findings computed from the harmonised record: the El Niño response of the January-May season, and the step across the change of sensor.
// Written with an AI assistant (Claude Code) during the hackathon, 15 Nov 2026; see README.
// Run after build-data.mjs: node pipeline/build-findings.mjs   (no dependencies; Node 18+)
//
// El Niño years: January-March value of +0.5 or more on NOAA's Oceanic Niño Index
// (https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt), full years 2003-2025. The one list used everywhere on the site.
// Season: January-May hotspots_harmonised. Response = median of the El Niño seasons / median of the other seasons.
// Test: one-sided permutation test, 2,000 shuffles of which 8 of the 23 years count as El Niño, fixed seed.
// An area whose other-seasons median is below MIN_OTHER_MEDIAN is "too few fires to tell" and gets no ratio.
// Sensor step = mean of 2012-2016 / mean of 2007-2011, three ways: raw stitched (MODIS Aqua to 2011, VIIRS Suomi NPP from 2012),
// harmonised, and MODIS Aqua alone in both periods (the one satellite that flew through both).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "data");
const AI_NOTE = "Generated by pipeline/build-findings.mjs, which was written with AI assistance (Claude Code, Anthropic) during NASA Space Apps 2026; see README.";

const EL_NINO_YEARS = [2003, 2005, 2010, 2015, 2016, 2019, 2020, 2024];
const YEARS = Array.from({ length: 23 }, (_, i) => 2003 + i); // 2003-2025
const SEASON_MONTHS = [1, 2, 3, 4, 5];
const MIN_OTHER_MEDIAN = 20;
const SHUFFLES = 2000, SEED = 20261115;
const MODIS_YEARS = YEARS.filter((y) => y <= 2011), VIIRS_YEARS = YEARS.filter((y) => y >= 2013);

const areas = JSON.parse(fs.readFileSync(path.join(OUT, "areas.json"), "utf8"));
const lines = fs.readFileSync(path.join(OUT, "monthly.csv"), "utf8").trim().split(/\r?\n/);
const head = lines[0].split(",");
const ix = Object.fromEntries(head.map((h, i) => [h, i]));
const rows = new Map(); // area_id -> month -> row
for (const l of lines.slice(1)) {
  const c = l.split(",");
  const id = c[ix.area_id];
  if (!rows.has(id)) rows.set(id, new Map());
  rows.get(id).set(c[ix.month], { h: +c[ix.hotspots_harmonised], aqua: +c[ix.modis_aqua], snpp: +c[ix.viirs_snpp] });
}

const median = (a) => { const s = [...a].sort((x, y) => x - y); const n = s.length; return n ? (n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2) : null; };
const mean = (a) => a.reduce((x, y) => x + y, 0) / a.length;
const r1 = (x) => Math.round(x * 10) / 10, r3 = (x) => Math.round(x * 1000) / 1000, r4 = (x) => Math.round(x * 10000) / 10000;
const ym = (y, m) => `${y}-${String(m).padStart(2, "0")}`;
const season = (id, y) => SEASON_MONTHS.reduce((s, m) => s + (rows.get(id).get(ym(y, m))?.h ?? 0), 0);

// Seeded random numbers (mulberry32), so every rebuild gives the same p-values.
function rng(seed) {
  let a = seed >>> 0;
  return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
// The same 2,000 shuffles for every area: each is a random choice of 8 of the 23 years.
const rand = rng(SEED);
const shuffles = Array.from({ length: SHUFFLES }, () => {
  const idx = YEARS.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [idx[i], idx[j]] = [idx[j], idx[i]]; }
  return new Set(idx.slice(0, EL_NINO_YEARS.length));
});

function response(values, years) {
  const nino = years.map((y, i) => (EL_NINO_YEARS.includes(y) ? values[i] : null)).filter((v) => v != null);
  const other = years.map((y, i) => (EL_NINO_YEARS.includes(y) ? null : values[i])).filter((v) => v != null);
  return { nino, other, ninoMedian: median(nino), otherMedian: median(other) };
}

function elNino(id) {
  const values = YEARS.map((y) => season(id, y));
  const { nino, ninoMedian, otherMedian } = response(values, YEARS);
  const busiest = YEARS[values.indexOf(Math.max(...values))];
  const out = { ninoMedian: r1(ninoMedian), otherMedian: r1(otherMedian), ninoMin: r1(Math.min(...nino)), ninoMax: r1(Math.max(...nino)), busiestSeason: busiest, busiestSeasonElNino: EL_NINO_YEARS.includes(busiest) && Math.max(...values) > 0 };
  if (!(otherMedian >= MIN_OTHER_MEDIAN)) return { ...out, testable: false, ratio: null, p: null };
  const ratio = ninoMedian / otherMedian;
  // One-sided: how often does a random choice of 8 years give a ratio at least as large? p = (hits + 1) / (shuffles + 1).
  let hits = 0;
  for (const s of shuffles) {
    const a = [], b = [];
    values.forEach((v, i) => (s.has(i) ? a : b).push(v));
    const mb = median(b);
    if (mb > 0 && median(a) / mb >= ratio - 1e-12) hits++;
  }
  return { ...out, testable: true, ratio: r3(ratio), p: r4((hits + 1) / (SHUFFLES + 1)) };
}
function subRatio(id, years) {
  const { ninoMedian, otherMedian } = response(years.map((y) => season(id, y)), years);
  return otherMedian > 0 ? r3(ninoMedian / otherMedian) : null;
}

const results = {};
for (const a of areas) {
  results[a.id] = elNino(a.id);
  if (a.level !== "province") Object.assign(results[a.id], { ratioModisYears: subRatio(a.id, MODIS_YEARS), ratioViirsYears: subRatio(a.id, VIIRS_YEARS) });
}
const provinces = areas.filter((a) => a.level === "province");
const testable = provinces.filter((a) => results[a.id].testable);
const national = YEARS.map((y) => ({ y, v: season("ph", y) })).sort((a, b) => b.v - a.v);
const summary = {
  provinces: provinces.length,
  provincesTestable: testable.length,
  provincesAbove2: testable.filter((a) => results[a.id].ratio > 2).length,
  provincesAbove1_5: testable.filter((a) => results[a.id].ratio > 1.5).length,
  provincesBelow1: testable.filter((a) => results[a.id].ratio < 1).length,
  provincesP05: testable.filter((a) => results[a.id].p < 0.05).length,
  provincesP05ExpectedByChance: r1(testable.length * 0.05),
  provincesBusiestSeasonElNino: provinces.filter((a) => results[a.id].busiestSeasonElNino).length,
  nationalTop8: national.slice(0, 8).map((d) => d.y),
  nationalTop8ElNino: national.slice(0, 8).filter((d) => EL_NINO_YEARS.includes(d.y)).length,
};
fs.writeFileSync(path.join(OUT, "elnino.json"), JSON.stringify({
  aiAssistance: AI_NOTE,
  rules: `El Niño years: January-March Oceanic Niño Index (NOAA) of +0.5 or more. Season: January-May, full years ${YEARS[0]}-${YEARS[YEARS.length - 1]}. Ratio = median of the El Niño seasons / median of the other seasons. p: one-sided permutation test, ${SHUFFLES} random choices of ${EL_NINO_YEARS.length} of the ${YEARS.length} years (seed ${SEED}), p = (hits + 1) / (shuffles + 1). Areas whose other-seasons median is below ${MIN_OTHER_MEDIAN} hotspots are not tested. Cross-check for country and regions: the same ratio inside the MODIS years (${MODIS_YEARS[0]}-${MODIS_YEARS[MODIS_YEARS.length - 1]}) and the VIIRS years (${VIIRS_YEARS[0]}-${VIIRS_YEARS[VIIRS_YEARS.length - 1]}).`,
  elNinoYears: EL_NINO_YEARS, years: [YEARS[0], YEARS[YEARS.length - 1]], seasonMonths: SEASON_MONTHS, minOtherMedian: MIN_OTHER_MEDIAN, shuffles: SHUFFLES, seed: SEED,
  modisYears: [MODIS_YEARS[0], MODIS_YEARS[MODIS_YEARS.length - 1]], viirsYears: [VIIRS_YEARS[0], VIIRS_YEARS[VIIRS_YEARS.length - 1]],
  summary, areas: results,
}, null, 1));

// ---------- the step across the change of sensor ----------
const yearSum = (id, y, f) => { let s = 0; for (let m = 1; m <= 12; m++) s += f(rows.get(id).get(ym(y, m))); return s; };
const BEFORE = [2007, 2008, 2009, 2010, 2011], AFTER = [2012, 2013, 2014, 2015, 2016];
function step(id, fBefore, fAfter) {
  const b = mean(BEFORE.map((y) => yearSum(id, y, fBefore))), a = mean(AFTER.map((y) => yearSum(id, y, fAfter)));
  return b > 0 ? r4(a / b) : null;
}
const seam = {};
for (const a of areas.filter((x) => x.level !== "province")) {
  seam[a.id] = {
    raw: step(a.id, (r) => r.aqua, (r) => r.snpp),
    harmonised: step(a.id, (r) => r.h, (r) => r.h),
    aquaAlone: step(a.id, (r) => r.aqua, (r) => r.aqua),
  };
}
const regionIds = areas.filter((a) => a.level === "region").map((a) => a.id);
const offs = regionIds.map((id) => ({ id, off: Math.abs(seam[id].harmonised / seam[id].aquaAlone - 1) }));
fs.writeFileSync(path.join(OUT, "seam.json"), JSON.stringify({
  aiAssistance: AI_NOTE,
  rules: `Step = mean yearly total ${AFTER[0]}-${AFTER[AFTER.length - 1]} / mean yearly total ${BEFORE[0]}-${BEFORE[BEFORE.length - 1]}, from monthly.csv. raw: MODIS Aqua count to 2011, VIIRS Suomi NPP count from 2012. harmonised: hotspots_harmonised. aquaAlone: MODIS Aqua count in both periods.`,
  before: [BEFORE[0], BEFORE[BEFORE.length - 1]], after: [AFTER[0], AFTER[AFTER.length - 1]],
  summary: {
    regionsRawMedian: r4(median(regionIds.map((id) => seam[id].raw))),
    regionsRawMin: r4(Math.min(...regionIds.map((id) => seam[id].raw))),
    regionsRawMax: r4(Math.max(...regionIds.map((id) => seam[id].raw))),
    regionsHarmonisedVsAquaMedianOff: r3(median(offs.map((d) => d.off))),
    regionsHarmonisedVsAquaOff: Object.fromEntries(offs.map((d) => [d.id, r3(d.off)])),
  },
  areas: seam,
}, null, 1));

const show = (id) => { const r = results[id]; return `${id}: ${r.ratio ?? "-"} (${r.ninoMedian} / ${r.otherMedian}) p=${r.p} modis=${r.ratioModisYears} viirs=${r.ratioViirsYears}`; };
console.log(show("ph"));
for (const id of regionIds.sort((a, b) => results[a].ratio - results[b].ratio)) console.log(show(id));
console.log("summary", summary);
console.log("strongest", testable.sort((a, b) => results[b.id].ratio - results[a.id].ratio).slice(0, 8).map((a) => `${a.name} ${results[a.id].ratio.toFixed(1)}`).join("; "));
console.log("weakest", testable.slice(-4).map((a) => `${a.name} ${results[a.id].ratio.toFixed(1)}`).join("; "));
console.log("seam ph", seam.ph, "regions", JSON.parse(fs.readFileSync(path.join(OUT, "seam.json"), "utf8")).summary);
